# * STRING INTRODUCTION :-
"""
# STRING :- is a collection of characters given from the keyboard enclosed in single quotes.
# STRING is IMMUTABLE.
"""

s1 = "Hello"
print(s1[0])  # [] --> called as subscript operator

print("---------------------------------")

print(len(s1))  # len() is a function used for finding the length of a string

print("---------------------------------")

for char in s1:
    print(char)  # Traversing in a string

print("---------------------------------")

print(s1[1:7])  # This in indexing --> [start:stop:step]

print("---------------------------------")
